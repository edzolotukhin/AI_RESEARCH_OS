from __future__ import annotations

from typing import Protocol

from domain.research_authority import ComposedResearchAuthority, ResearchAuthorityExtension


class AuthorityExtensionRepository(Protocol):
    def create_or_get(self, extension: ResearchAuthorityExtension) -> ResearchAuthorityExtension: ...
    def get_by_id(self, extension_id: str) -> ResearchAuthorityExtension | None: ...
    def get_by_idempotency_key(self, project_id: str, idempotency_key: str) -> ResearchAuthorityExtension | None: ...


class ComposedAuthorityRepository(Protocol):
    def create_or_get(self, composition: ComposedResearchAuthority) -> ComposedResearchAuthority: ...
    def get_by_id(self, composition_id: str) -> ComposedResearchAuthority | None: ...
    def get_by_digest(self, composition_digest: str) -> ComposedResearchAuthority | None: ...
